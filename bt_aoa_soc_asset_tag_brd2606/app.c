// Optional per-tag pairing/bonding hardening (Layer 1 of the CS auth scheme).
// ---------------------------------------------------------------------------
// DEFAULT OFF. When CS_TAG_REQUIRE_BOND == 0 the tag behaves exactly as before
// (stack-default Security Manager, JustWorks, no bonding requested) so the
// working CS/AoA/IMU pipeline is untouched.
//
// When enabled (-DCS_TAG_REQUIRE_BOND=1) the tag offers Secure-Connections-
// only, bondable, debug-keys-rejected pairing. On this NoInputNoOutput board
// the over-the-air association is necessarily JustWorks: there is no
// display/keyboard, and a static factory OOB confirm is invalid for LE Secure
