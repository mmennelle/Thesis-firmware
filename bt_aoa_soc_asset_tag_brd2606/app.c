// per-pairing ECDH public key (verified against SDK 2025.12.3 sl_bt_sm_set_oob,
// whose random/confirm are OUT params generated by the stack). The defensible
// per-tag identity guarantee therefore comes from Layer 2 (host-side IRK pin);
// this layer only makes the link SC-only, bonded and encrypted, and is meant to
// be enrolled at the bench together with the matching initiator-side change.
#ifndef CS_TAG_REQUIRE_BOND
#define CS_TAG_REQUIRE_BOND 0
#endif

